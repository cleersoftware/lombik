  function svgEl(tag, attrs = {}, text = '') {
    const el = document.createElementNS('http://www.w3.org/2000/svg', tag);
    for (const [key, value] of Object.entries(attrs)) {
      el.setAttribute(key, value);
    }
    if (text !== '') el.textContent = text;
    return el;
  }

  function niceNumber(value) {
    if (!Number.isFinite(value) || value <= 0) return 1;
    const exp = Math.floor(Math.log10(value));
    const fraction = value / Math.pow(10, exp);
    let nice;
    if (fraction <= 1) nice = 1;
    else if (fraction <= 2) nice = 2;
    else if (fraction <= 5) nice = 5;
    else nice = 10;
    return nice * Math.pow(10, exp);
  }

  function getYDomain(values) {
    const min = Math.min(0, ...values);
    const max = Math.max(0, ...values);
    const range = max - min;
    const niceRange = niceNumber(range) || 1;
    return { min, max: min + niceRange, range: niceRange };
  }

  function formatTick(value) {
    if (Number.isInteger(value)) return String(value);
    return String(Math.round(value * 100) / 100);
  }

  function parseArray(value, fallback = []) {
    if (!value) return fallback;
    try {
      const parsed = JSON.parse(value);
      return Array.isArray(parsed) ? parsed : fallback;
    } catch (_) {
      return fallback;
    }
  }

  class ChartBase extends HTMLElement {
    static get observedAttributes() {
      return ['x', 'y', 'data', 'labels', 'values', 'size', 'legend', 'theme', 'x_title', 'y_title', 'x-title', 'y-title'];
    }

    constructor() {
      super();
      this.attachShadow({ mode: 'open' });
      this.aspectRatio = '2 / 1';
      this.viewBox = '0 0 800 400';
    }

    connectedCallback() {
      this.render();
    }

    attributeChangedCallback(name, oldValue, newValue) {
      if (oldValue !== newValue && this.isConnected) {
        this.render();
      }
    }

    getTheme() {
        const themeAttr = this.getAttribute('theme') || '';
        const defaultTheme = (window.ChartThemes && window.ChartThemes.default) || ChartThemes.default;
        let baseTheme = { ...defaultTheme };
        let variantThemes = {}; 

        if (themeAttr.trim().startsWith('{')) {
            try {
            const inline = JSON.parse(themeAttr);
            return { ...baseTheme, ...inline };
            } catch (_) {
            // fall through to string parsing
            }
        }

        const tokens = themeAttr.split(/\s+/).filter(Boolean);
        for (const token of tokens) {
            if (token.includes(':')) {
            const [variant, themeName] = token.split(':');
            if (variant && themeName) {
                variantThemes[variant.trim()] = themeName.trim();
            }
            } else {
            // No variant -> base theme
            if (window.ChartThemes && window.ChartThemes[token]) {
                baseTheme = { ...defaultTheme, ...window.ChartThemes[token] };
            }
            }
        }

        const isDark = 
            document.documentElement.classList.contains('dark') ||
            (window.matchMedia && window.matchMedia('(prefers-color-scheme: dark)').matches);

        const activeVariant = isDark ? 'dark' : 'light';

        if (variantThemes[activeVariant] && window.ChartThemes && window.ChartThemes[variantThemes[activeVariant]]) {
            return { ...baseTheme, ...window.ChartThemes[variantThemes[activeVariant]] };
        }

        if (window.matchVariant) {
            for (const [variant, themeName] of Object.entries(variantThemes)) {
            if (variant !== 'dark' && variant !== 'light') {
                try {
                if (window.matchVariant(variant)) {
                    if (window.ChartThemes && window.ChartThemes[themeName]) {
                    return { ...baseTheme, ...window.ChartThemes[themeName] };
                    }
                }
                } catch (_) {}
            }
            }
        }

        return baseTheme;
        }

    getData() {
      const dataAttr = this.getAttribute('data');
      if (!dataAttr) return null;
      try {
        const parsed = JSON.parse(dataAttr);
        if (parsed && typeof parsed === 'object' && !Array.isArray(parsed)) {
          return parsed;
        }
      } catch (_) {}
      return null;
    }

    getX() {
      const data = this.getData();
      if (data) return Object.keys(data);
      return parseArray(this.getAttribute('x') || this.getAttribute('x-values') || '[]');
    }

    getY() {
      const data = this.getData();
      if (data) {
        return Object.values(data).map(Number).filter(Number.isFinite);
      }
      return parseArray(this.getAttribute('y') || this.getAttribute('y-values') || '[]')
        .map(Number)
        .filter(Number.isFinite);
    }

    getLabels() {
      const data = this.getData();
      if (data) return Object.keys(data);
      return parseArray(this.getAttribute('labels') || '[]');
    }

    getValues() {
      const data = this.getData();
      if (data) {
        return Object.values(data).map(Number).filter(Number.isFinite);
      }
      return parseArray(this.getAttribute('values') || '[]')
        .map(Number)
        .filter(Number.isFinite);
    }

    render() {
      const theme = this.getTheme();
      const style = document.createElement('style');
      style.textContent = `
        :host {
          display: block;
          width: 100%;
          aspect-ratio: ${this.aspectRatio};
          box-sizing: border-box;
          font-family: ${theme['font-family']};
          color: ${theme['text-color']};
        }
        svg {
          display: block;
          width: 100%;
          height: 100%;
        }
      `;

      const content = this.createContent(theme);
      this.shadowRoot.replaceChildren(style, ...content);
    }

    createContent(theme) {
      return [svgEl('svg', { viewBox: this.viewBox, 'font-family': theme['font-family'] })];
    }
  }

  class BarChartElement extends ChartBase {
    constructor() {
      super();
      this.aspectRatio = '2 / 1';
      this.viewBox = '0 0 800 400';
    }

    createContent(theme) {
      const svg = svgEl('svg', { viewBox: this.viewBox, 'font-family': theme['font-family'] });

      if (theme.background && theme.background !== 'transparent') {
        svg.append(svgEl('rect', { width: '100%', height: '100%', fill: theme.background }));
      }

      const x = this.getX();
      const y = this.getY();
      if (y.length === 0) return [svg];

      const n = y.length;
      const margin = { top: 40, right: 20, bottom: 50, left: 60 };
      const width = 800 - margin.left - margin.right;
      const height = 400 - margin.top - margin.bottom;
      const domain = getYDomain(y);
      const yScale = height / domain.range;

      for (let i = 0; i <= 4; i++) {
        const value = domain.min + domain.range * i / 4;
        const yy = margin.top + height - (value - domain.min) * yScale;

        svg.append(svgEl('line', {
          x1: margin.left,
          y1: yy,
          x2: margin.left + width,
          y2: yy,
          stroke: theme['grid-color'],
          'stroke-width': '1'
        }));

        svg.append(svgEl('text', {
          x: margin.left - 10,
          y: yy + 4,
          'text-anchor': 'end',
          'font-size': theme['font-size'],
          fill: theme['text-color']
        }, formatTick(value)));
      }

      const band = width / n;
      const barWidth = band * 0.7;

      for (let i = 0; i < n; i++) {
        const value = y[i];
        const cx = margin.left + band * i + band / 2;
        const xPos = margin.left + band * i + (band - barWidth) / 2;
        const yPos = margin.top + height - (value - domain.min) * yScale;
        const barHeight = (value - domain.min) * yScale;

        svg.append(svgEl('rect', {
          x: xPos,
          y: yPos,
          width: barWidth,
          height: barHeight,
          fill: theme['bar-color'],
          stroke: theme['bar-border'],
          'stroke-width': theme['bar-border-width'] || '1'
        }));

        svg.append(svgEl('text', {
          x: cx,
          y: margin.top + height + 20,
          'text-anchor': 'middle',
          'font-size': theme['font-size'],
          fill: theme['text-color']
        }, String(x[i] !== undefined ? x[i] : i + 1)));
      }

      svg.append(svgEl('line', {
        x1: margin.left,
        y1: margin.top + height,
        x2: margin.left + width,
        y2: margin.top + height,
        stroke: theme['axis-color'],
        'stroke-width': '1.5'
      }));

      svg.append(svgEl('line', {
        x1: margin.left,
        y1: margin.top,
        x2: margin.left,
        y2: margin.top + height,
        stroke: theme['axis-color'],
        'stroke-width': '1.5'
      }));

      const xTitle = this.getAttribute('x_title') || this.getAttribute('x-title') || '';
      const yTitle = this.getAttribute('y_title') || this.getAttribute('y-title') || '';

      if (xTitle) {
        svg.append(svgEl('text', {
          x: margin.left + width / 2,
          y: 390,
          'text-anchor': 'middle',
          'font-size': theme['font-size'],
          fill: theme['text-color']
        }, xTitle));
      }

      if (yTitle) {
        const yy = margin.top + height / 2;
        svg.append(svgEl('text', {
          x: 20,
          y: yy,
          'text-anchor': 'middle',
          'font-size': theme['font-size'],
          fill: theme['text-color'],
          transform: `rotate(-90 20 ${yy})`
        }, yTitle));
      }

      return [svg];
    }
  }

